"""Export the trained autoencoder to TFLite (float32 and full-integer int8)
and compare size and detection quality.

    python -m ml.export_tflite --variant norm

Writes models/autoencoder_<variant>_fp32.tflite, models/autoencoder_<variant>_int8.tflite,
models/model_data.h (C array for TFLite Micro) and models/export_report_<variant>.json.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import tensorflow as tf
from tensorflow import keras

from ml.data import VARIANTS, load_dataset
from ml.evaluate import detection_report, threshold_from_normal

ROOT = Path(__file__).resolve().parents[1]
MODELS = ROOT / "models"


def convert(model: keras.Model, rep: np.ndarray | None) -> bytes:
    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    if rep is not None:
        conv.optimizations = [tf.lite.Optimize.DEFAULT]
        conv.representative_dataset = lambda: (
            [rep[i:i + 1][..., None].astype(np.float32)] for i in range(len(rep)))
        conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
        conv.inference_input_type = tf.int8
        conv.inference_output_type = tf.int8
    return conv.convert()


def tflite_errors(tfl: bytes, x: np.ndarray) -> np.ndarray:
    """Per-window reconstruction MSE through the TFLite interpreter,
    applying the same int8 (de)quantisation a microcontroller would."""
    it = tf.lite.Interpreter(model_content=tfl)
    it.allocate_tensors()
    inp, out = it.get_input_details()[0], it.get_output_details()[0]
    errs = np.empty(len(x), dtype=np.float32)
    for i, w in enumerate(x):
        v = w[None, :, None].astype(np.float32)
        if inp["dtype"] == np.int8:
            s, z = inp["quantization"]
            v = np.clip(np.round(v / s + z), -128, 127).astype(np.int8)
        it.set_tensor(inp["index"], v)
        it.invoke()
        r = it.get_tensor(out["index"]).astype(np.float32)
        if out["dtype"] == np.int8:
            s, z = out["quantization"]
            r = (r - z) * s
        errs[i] = np.mean((r[0, :, 0] - w) ** 2)
    return errs


def to_c_header(tfl: bytes, name: str = "g_model") -> str:
    rows = []
    for i in range(0, len(tfl), 12):
        rows.append(", ".join(f"0x{b:02x}" for b in tfl[i:i + 12]))
    body = ",\n  ".join(rows)
    return (
        "// Auto-generated by ml/export_tflite.py: int8 TFLite model for TFLite Micro.\n"
        "#pragma once\n"
        "#include <cstdint>\n\n"
        f"alignas(16) const unsigned char {name}[] = {{\n  {body}\n}};\n"
        f"const unsigned int {name}_len = {len(tfl)};\n"
    )


def main(variant: str = "norm") -> dict:
    ds = load_dataset(variant)
    model = keras.models.load_model(MODELS / f"autoencoder_{variant}.keras")

    fp32 = convert(model, None)
    int8 = convert(model, ds.train[:300])
    (MODELS / f"autoencoder_{variant}_fp32.tflite").write_bytes(fp32)
    (MODELS / f"autoencoder_{variant}_int8.tflite").write_bytes(int8)
    if variant == "norm":
        (MODELS / "model_data.h").write_text(to_c_header(int8))

    report = {"variant": variant, "size_bytes": {"fp32": len(fp32), "int8": len(int8)}}
    for name, tfl in [("fp32", fp32), ("int8", int8)]:
        val = tflite_errors(tfl, ds.val)
        test = tflite_errors(tfl, ds.test_x)
        report[name] = detection_report(test, ds.test_y, ds.test_label, threshold_from_normal(val))
    # int8 input/output quantisation parameters, needed by the firmware
    it = tf.lite.Interpreter(model_content=int8)
    inp, out = it.get_input_details()[0], it.get_output_details()[0]
    report["int8_quant"] = {"input_scale": float(inp["quantization"][0]),
                            "input_zero_point": int(inp["quantization"][1]),
                            "output_scale": float(out["quantization"][0]),
                            "output_zero_point": int(out["quantization"][1])}
    (MODELS / f"export_report_{variant}.json").write_text(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))
    return report


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--variant", choices=VARIANTS, default="norm")
    a = p.parse_args()
    main(a.variant)
